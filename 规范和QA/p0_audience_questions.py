# 执行批量添加
print("=== P0修复：GEO-06旧文添加观众质疑模块 ===\n")

geo06_files = sorted([f for f in os.listdir(base_dir) if f.startswith('GEO-06-') and f.endswith('.html')])
fixed_count = 0
skipped_count = 0

for filename in geo06_files:
    filepath = os.path.join(base_dir, filename)
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 检查是否已有观众质疑模块
    if 'audience-question' in content or '观众质疑' in content:
        print(f"  ⏭️ {filename} 已有观众质疑模块，跳过")
        skipped_count += 1
        continue
    
    # 获取该文章的质疑内容
    questions = audience_questions.get(filename)
    if not questions:
        print(f"  ⚠️ {filename} 未定义质疑内容，跳过")
        continue
    
    # 构建观众质疑模块HTML
    audience_html = '<div class="audience-questions" style="margin:32px 0;">\n'
    audience_html += '  <h2 style="font-size:1.2em;color:#5A3A1F;margin-bottom:16px;border-bottom:2px solid #d4c4a8;padding-bottom:8px;">观众质疑</h2>\n'
    for i, (q, a) in enumerate(questions, 1):
        audience_html += f'  <div class="audience-question" style="margin-bottom:20px;padding:16px;background:#faf6f0;border-radius:8px;border-left:3px solid #c9a96e;">\n'
        audience_html += f'    <div class="question" style="font-weight:bold;color:#5A3A1F;margin-bottom:8px;">{q}</div>\n'
        audience_html += f'    <div class="answer" style="color:#6B5B4E;line-height:1.8;">{a}</div>\n'
        audience_html += f'  </div>\n'
    audience_html += '</div>\n\n'
    
    # 在"常见问题"之前插入观众质疑模块
    faq_pattern = r'(<h2[^>]*>常见问题</h2>)'
    if re.search(faq_pattern, content):
        new_content = re.sub(faq_pattern, audience_html + r'\1', content, count=1)
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(new_content)
        fixed_count += 1
        print(f"  ✅ {filename}（{len(questions)}个质疑）")
    else:
        print(f"  ⚠️ {filename} 未找到常见问题标题，跳过")

print(f"\n=== 完成：修复 {fixed_count} 篇，跳过 {skipped_count} 篇 ===")
